import struct, capstone, sys

f = open(r"G:\SteamLibrary\steamapps\common\Sonic Adventure 2\mods\SA2 Six Garden Expansion Dev\recon_text.bin", "rb").read()
BASE = 0x401000
LO, HI = 0x672700, 0x678600
T, F = 0xC75078, 0x1A4A974
NT, NF = 33 * 16, 33 * 4

md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
md.detail = True
ops = {}  # address of 4-byte field -> (kind of field, insn text)
for i in md.disasm(f[LO - BASE:HI - BASE], LO):
    d = i.disp_offset
    if d:
        for op in i.operands:
            if op.type == capstone.x86.X86_OP_MEM and op.mem.disp:
                ops[i.address + d] = ("disp", op.mem.disp & 0xFFFFFFFF, i)
    if i.imm_offset and i.imm_size == 4:
        for op in i.operands:
            if op.type == capstone.x86.X86_OP_IMM:
                ops[i.address + i.imm_offset] = ("imm", op.imm & 0xFFFFFFFF, i)

table, end0, end4, flags, counts, unknown = [], [], [], [], [], []
for a, (k, v, i) in sorted(ops.items()):
    raw = struct.unpack_from("<I", f, a - BASE)[0]
    if raw != v:
        continue
    if T <= v < T + NT:
        table.append(a)
    elif v == T + NT:
        end0.append(a)
    elif v == T + NT + 4:
        end4.append(a)
    elif F <= v < F + NF:
        flags.append(a)
    elif T - 16 <= v <= T + NT + 16 or F - 8 <= v <= F + NF + 8:
        unknown.append((a, hex(v), i.mnemonic + " " + i.op_str))

# every raw hit in the module must be explained
raw_hits = []
for o in range(LO - BASE, HI - BASE - 3):
    v = struct.unpack_from("<I", f, o)[0]
    if T <= v <= T + NT + 4 or F <= v < F + NF:
        raw_hits.append(BASE + o)
explained = set(table + end0 + end4 + flags)
missing = [hex(a) for a in raw_hits if a not in explained]
print("table", len(table), "end0", [hex(a) for a in end0], "end4", [hex(a) for a in end4],
      "flags", len(flags))
print("unknown", unknown)
print("raw hits not explained", missing)

# loop-count compares (cmp reg, 0x21) in the navigation loops
count_sites = []
for a in (0x677ccf, 0x677da1, 0x677f3b, 0x6780da):
    b = f[a - BASE:a - BASE + 3]
    print(hex(a), b.hex())
    count_sites.append(a)


def arr(name, xs):
    return "constexpr std::uintptr_t %s[] = {%s};\n" % (name, ", ".join(hex(x) for x in xs))


with open(r"C:\Users\leg4c\Desktop\SA Test Mod\src\StageSelectSites.h", "w") as out:
    out.write("// Generated by tools\\gen_stage_select_sites.py from the live decrypted code.\n#pragma once\n#include <cstdint>\n\n")
    out.write(arr("StageTableSites", table))
    out.write(arr("StageTableEnd0Sites", end0))
    out.write(arr("StageTableEnd4Sites", end4))
    out.write(arr("StageFlagSites", flags))
    out.write(arr("StageCountSites", count_sites))
